//! Layout tree and line boxes.

use std::sync::Arc;

use crate::document::style::ComputedStyle;
use crate::geom::Rect;
use crate::text::ShapedText;

/// Identifies a layout box.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub(crate) struct BoxId(pub(crate) u32);

impl BoxId {
    pub(crate) fn index(self) -> usize {
        self.0 as usize
    }
}

/// A block-level layout box.
#[derive(Clone, Debug)]
pub(crate) struct LayoutBox {
    /// The originating DOM node.
    pub(crate) node: crate::document::NodeId,
    /// The containing box, if any.
    pub(crate) parent: Option<BoxId>,
    /// Computed style.
    pub(crate) style: ComputedStyle,
    /// Border box.
    pub(crate) rect: Rect,
    /// Content box.
    pub(crate) content: Rect,
    /// Child boxes in flow order.
    pub(crate) children: Vec<BoxId>,
    /// Line boxes generated by inline content.
    pub(crate) lines: Vec<LineBox>,
    /// Decoded image content, when the box is an image.
    pub(crate) image: Option<Arc<crate::image::DecodedImage>>,
    /// True when this box is placed as an atomic inline.
    pub(crate) atomic_inline: bool,
}

/// A line of inline content.
#[derive(Clone, Debug)]
pub(crate) struct LineBox {
    /// Text and atomic items in visual order.
    pub(crate) items: Vec<LineItem>,
    /// Height of the line.
    pub(crate) height: f32,
    /// Baseline position in page coordinates.
    pub(crate) baseline: f32,
}

/// An item placed on a line.
#[derive(Clone, Debug)]
#[allow(clippy::large_enum_variant)]
pub(crate) enum LineItem {
    /// A shaped text fragment.
    Text(TextFragment),
    /// An atomic inline box.
    Atomic(AtomicFragment),
}

/// A positioned text fragment.
#[derive(Clone, Debug)]
pub(crate) struct TextFragment {
    /// The style used for the fragment.
    pub(crate) style: ComputedStyle,
    /// Shaped glyphs, if a usable font was found.
    pub(crate) shaped: Option<Arc<ShapedText>>,
    /// Left edge in page coordinates.
    pub(crate) x: f32,
    /// Advance width.
    pub(crate) width: f32,
}

/// A positioned atomic inline box.
#[derive(Clone, Debug)]
pub(crate) struct AtomicFragment {
    /// The layout box that owns the atomic content.
    pub(crate) box_id: BoxId,
    /// Left edge of the border box in page coordinates.
    pub(crate) x: f32,
    /// Top edge of the border box in page coordinates.
    pub(crate) y: f32,
    /// Distance from the line baseline to the top of the margin box.
    pub(crate) ascent: f32,
    /// Top margin that separates the margin box from the border box.
    pub(crate) margin_top: f32,
}

/// The result of layout.
#[derive(Clone, Debug)]
pub(crate) struct LayoutTree {
    boxes: Vec<LayoutBox>,
    root: BoxId,
    height: f32,
}

impl LayoutTree {
    /// Creates a layout tree.
    pub(crate) fn new(boxes: Vec<LayoutBox>, root: BoxId, height: f32) -> Self {
        Self {
            boxes,
            root,
            height,
        }
    }

    /// Returns a box by identifier.
    pub(crate) fn get(&self, id: BoxId) -> &LayoutBox {
        &self.boxes[id.index()]
    }

    /// Returns the root box.
    pub(crate) fn root(&self) -> BoxId {
        self.root
    }

    /// Returns the document height in CSS pixels.
    pub(crate) fn height(&self) -> f32 {
        self.height
    }

    /// Returns all boxes.
    pub(crate) fn boxes(&self) -> &[LayoutBox] {
        &self.boxes
    }
}
